#!/usr/bin/env python3
"""Generate N component types for the alloc probes (run by MSBuild before compiling).

usage: gen_types.py <count> <prefix> <namespace> <out.cs>

Every type is `public struct <prefix>NNNN : IComponent { public int V; }`; names have the same
length, so a type name string has the same size for all of them. The dispatch helpers use only
API that exists since KenseiECS 2.1.1 (Pool<T>, Add, Remove, Filter().Inc<T>().End()).
The file is rewritten only when its content changes, so incremental builds stay incremental.
"""
import os
import sys


def main():
    if len(sys.argv) != 5:
        sys.stderr.write(__doc__)
        return 2
    count = int(sys.argv[1])
    prefix = sys.argv[2]
    namespace = sys.argv[3]
    out = sys.argv[4]
    width = max(4, len(str(count - 1)))

    def name(i):
        return "%s%0*d" % (prefix, width, i)

    lines = []
    w = lines.append
    w("// <auto-generated/> by Stand/alloc/tools/gen_types.py: %d component types." % count)
    w("using KenseiECS;")
    w("")
    w("namespace %s {" % namespace)
    for i in range(count):
        w("    public struct %s : IComponent { public int V; }" % name(i))
    w("")
    w("    public static class GenTypes {")
    w("        public const int Count = %d;" % count)
    w("        public const string Prefix = \"%s\";" % prefix)
    w("        public const int NameLength = %d;" % (len(prefix) + width))
    w("")
    w("        public static void CreatePool(World w, int t) {")
    w("            switch (t) {")
    for i in range(count):
        w("                case %d: w.Pool<%s>(); return;" % (i, name(i)))
    w("            }")
    w("        }")
    w("")
    w("        public static void AddAt(World w, Entity e, int t) {")
    w("            switch (t) {")
    for i in range(count):
        w("                case %d: w.Add(e, new %s { V = %d }); return;" % (i, name(i), i))
    w("            }")
    w("        }")
    w("")
    w("        public static void RemoveAt(World w, Entity e, int t) {")
    w("            switch (t) {")
    for i in range(count):
        w("                case %d: w.Remove<%s>(e); return;" % (i, name(i)))
    w("            }")
    w("        }")
    w("")
    w("        public static Filter IncFilter(World w, int t) {")
    w("            switch (t) {")
    for i in range(count):
        w("                case %d: return w.Filter().Inc<%s>().End();" % (i, name(i)))
    w("            }")
    w("            return null;")
    w("        }")
    w("")
    w("        public static System.Type TypeOf(int t) {")
    w("            switch (t) {")
    for i in range(count):
        w("                case %d: return typeof(%s);" % (i, name(i)))
    w("            }")
    w("            return null;")
    w("        }")
    w("    }")
    w("}")
    text = "\n".join(lines) + "\n"

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    try:
        with open(out, "r", encoding="utf-8") as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
